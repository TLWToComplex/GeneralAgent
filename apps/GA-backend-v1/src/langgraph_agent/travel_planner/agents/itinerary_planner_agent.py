_mcp_tools = None


def _get_mcp_tools():
    """获取 MCP 工具列表（首次调用时初始化）"""
    global _mcp_tools
    if _mcp_tools is not None:
        return _mcp_tools
    import concurrent.futures
    service_configs = TravelPlannerConfig.get_service_configs()
    with concurrent.futures.ThreadPoolExecutor(max_workers=1) as executor:
        future = executor.submit(
            asyncio.run,
            initialize_multiple_mcp_servers(service_configs, timeout=10.0)
        )
        tools = future.result(timeout=15)
    _mcp_tools = [tool for tool in tools if tool.name in _allowed_tools]
    print(f"[\033[92m成功\033[0m] 已加载 {len(_mcp_tools)} 个工具")
    return _mcp_tools


